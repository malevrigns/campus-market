import { test, expect } from '@playwright/test'

test('admin creates a capability and agent, publishes, rolls back and disables on mobile', async ({
  page,
}) => {
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/')
  await page.locator('.account-button').click()
  await page.locator('input[name="email"]').fill('studio@example.test')
  await page.locator('input[name="password"]').fill('Studio-test-only-123')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('.account-button .avatar')).toBeVisible()
  await page.goto('/#profile')
  await page.getByRole('button', { name: /Agent 工作室/ }).click()
  await expect(page.getByRole('heading', { name: '让助手，各有所长.' })).toBeVisible()
  await page.getByRole('button', { name: '能力目录', exact: true }).click()
  await page.getByRole('button', { name: '添加能力', exact: true }).click()
  await page.getByLabel('能力名称', { exact: true }).fill('校园模型测试')
  await page.getByLabel('能力描述', { exact: true }).fill('管理员创建的模型能力')
  await page.getByRole('button', { name: '保存能力', exact: true }).click()
  await expect(page.locator('.capability-list').getByText('校园模型测试', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '助手管理', exact: true }).click()
  await page.getByRole('button', { name: '新建助手', exact: true }).click()
  await page.getByLabel('助手名称', { exact: true }).fill('相机验货专家')
  await page.getByLabel('欢迎语', { exact: true }).fill('准备好检查你的下一台相机了吗？')
  await page.getByLabel('助手介绍', { exact: true }).fill('专注相机验货与二手交易细节')
  await page.getByLabel('系统提示词', { exact: true }).fill('你是相机验货专家。先询问型号，再给出检查清单。')
  await page.getByLabel('模型能力', { exact: true }).selectOption({ label: '校园模型测试' })
  await page.getByRole('checkbox', { name: /搜索校园好物/ }).check()
  await page.getByLabel('建议问题', { exact: false }).fill('如何检查快门？\n如何检查镜头？')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  let card = page.locator('.studio-card').filter({ hasText: '相机验货专家' })
  await expect(card.locator('.studio-state')).toHaveText('草稿')
  await card.getByRole('button', { name: '发布', exact: true }).click()
  await expect(card.locator('.studio-state')).toHaveText('已发布 v1')
  await expect(page.locator('.ant-message-notice')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/agent-studio-desktop.png', fullPage: true })
  await page.goto('/#agent')
  await page.getByRole('combobox', { name: '选择助手' }).selectOption({ label: '相机验货专家 · 暂不可用' })
  await expect(page.getByRole('heading', { name: /准备好检查你的下一台相机/ })).toBeVisible()
  await expect(page.locator('.agent-capabilities')).toContainText('搜索校园好物')
  await expect(page.locator('.agent-capabilities')).not.toContainText('查询我的订单')
  await expect(page.getByRole('button', { name: '发送问题', exact: true })).toBeDisabled()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#agent-admin')
  card = page.locator('.studio-card').filter({ hasText: '相机验货专家' })
  await card.getByRole('button', { name: '编辑草稿', exact: true }).click()
  await page.getByLabel('欢迎语', { exact: true }).fill('第二版欢迎语')
  await page.getByLabel('建议问题', { exact: false }).fill('')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(card.locator('.draft-notice')).toContainText('有未发布更改')
  await card.getByRole('button', { name: '发布', exact: true }).click()
  await expect(card.locator('.studio-state')).toHaveText('已发布 v2')
  await card.getByRole('button', { name: '版本历史', exact: true }).click()
  await page
    .locator('.version-row')
    .filter({ hasText: 'v1 ·' })
    .getByRole('button', { name: '恢复此版本', exact: true })
    .click()
  await page.getByRole('button', { name: '恢复并发布', exact: true }).click()
  await expect(card.locator('.studio-state')).toHaveText('已发布 v3')
  await expect(page.locator('.ant-modal:visible')).toHaveCount(0)
  await expect(page.locator('.ant-message-notice')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/agent-studio-mobile.png', fullPage: true })
  await card.getByRole('button', { name: '停用', exact: true }).click()
  await expect(card.locator('.studio-state')).toHaveText('已停用')
  await page.goto('/#agent')
  await expect(page.getByRole('combobox', { name: '选择助手' }).locator('option')).toHaveCount(1)
  expect(errors).toEqual([])
})
